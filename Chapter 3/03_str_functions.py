name = "harry"

print(len(name)) # length of the string
print(name.endswith("rry")) # check if the string ends with "y"
print(name.startswith("ha")) # check if the string starts with "H"

print(name.capitalize()) # capitalize the first letter of the string

print(name.upper())

print(name.replace("h", "j")) # replace h with j

print(name.isdigit()) # check if the string is a digit